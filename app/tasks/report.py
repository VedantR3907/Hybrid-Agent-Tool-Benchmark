from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


METRICS = [
    ("success_rate", "Success Rate", "{:.0%}"),
    ("avg_total_tokens", "Avg Tokens / Task", "{:.0f}"),
    ("avg_llm_turns", "Avg LLM Turns", "{:.2f}"),
    ("avg_tool_calls", "Avg Tool Calls", "{:.2f}"),
    ("avg_elapsed_ms", "Avg Elapsed (ms)", "{:.0f}"),
]


def load_summary(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise SystemExit(f"summary file not found: {path}. Run the benchmark first.")
    return json.loads(path.read_text(encoding="utf-8"))


def chart_metric(by_model: dict[str, dict[str, dict[str, float]]], metric_key: str, title: str, fmt: str, out_path: Path) -> None:
    models = list(by_model.keys())
    agents = sorted({agent for entries in by_model.values() for agent in entries})
    if not models or not agents:
        return

    width = 0.8 / len(agents)
    x_positions = list(range(len(models)))

    fig, ax = plt.subplots(figsize=(max(6, 1.6 * len(models)), 4.5))
    for agent_idx, agent in enumerate(agents):
        values = [by_model[m].get(agent, {}).get(metric_key, 0.0) for m in models]
        offsets = [x + (agent_idx - (len(agents) - 1) / 2) * width for x in x_positions]
        bars = ax.bar(offsets, values, width=width, label=agent)
        for bar, value in zip(bars, values):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height(),
                fmt.format(value),
                ha="center",
                va="bottom",
                fontsize=8,
            )

    ax.set_xticks(x_positions)
    ax.set_xticklabels(models, rotation=15, ha="right")
    ax.set_ylabel(title)
    ax.set_title(title)
    ax.legend(title="Agent")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_path, dpi=140)
    plt.close(fig)


def render_findings(summary: dict[str, Any], chart_files: list[Path], out_path: Path) -> None:
    by_model = summary.get("aggregates_by_model", {})
    models = summary.get("models", [])
    skipped = summary.get("skipped_models", [])

    lines: list[str] = []
    lines.append("# Findings: Function vs CLI Agent across Ollama Cloud models")
    lines.append("")
    lines.append("This report is auto-generated by `python -m app.tasks.report` from `runs/latest-summary.json`.")
    lines.append("")
    lines.append(f"- Models requested: {', '.join(models) if models else '(none)'}")
    if skipped:
        lines.append(f"- Models skipped: {', '.join(s['model'] for s in skipped)}")
    lines.append(f"- Suite: {summary.get('suite', 'unknown')}")
    lines.append("")
    lines.append("## Charts")
    lines.append("")
    for chart in chart_files:
        lines.append(f"![{chart.stem}]({chart.as_posix()})")
        lines.append("")

    lines.append("## Per-model x Agent metrics")
    lines.append("")
    lines.append("| Model | Agent | Runs | Success | Tokens | Turns | Tool Calls | Elapsed (ms) |")
    lines.append("|---|---|---:|---:|---:|---:|---:|---:|")
    for model, by_agent in by_model.items():
        for agent, metrics in by_agent.items():
            lines.append(
                f"| {model} | {agent} | {int(metrics['runs'])} | "
                f"{metrics['success_rate']:.0%} | {metrics['avg_total_tokens']:.0f} | "
                f"{metrics['avg_llm_turns']:.2f} | {metrics['avg_tool_calls']:.2f} | "
                f"{metrics['avg_elapsed_ms']:.0f} |"
            )
    lines.append("")

    lines.append("## Headline observations")
    lines.append("")
    headlines = derive_headlines(by_model)
    if headlines:
        for h in headlines:
            lines.append(f"- {h}")
    else:
        lines.append("- Not enough data to derive headlines yet.")
    lines.append("")

    lines.append("## Notes")
    lines.append("")
    lines.append("- Bullet points above are auto-derived from aggregates. Treat them as starting prompts, not conclusions.")
    lines.append("- Expand each into a real finding with a transcript link from `runs/` if you want to publish this.")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")


def derive_headlines(by_model: dict[str, dict[str, dict[str, float]]]) -> list[str]:
    headlines: list[str] = []
    for model, by_agent in by_model.items():
        fn = by_agent.get("function")
        cli = by_agent.get("cli")
        if not fn or not cli:
            continue
        if fn["success_rate"] != cli["success_rate"]:
            winner = "CLI" if cli["success_rate"] > fn["success_rate"] else "Function"
            headlines.append(
                f"On {model}, {winner} agent had the higher success rate "
                f"(function {fn['success_rate']:.0%} vs cli {cli['success_rate']:.0%})."
            )
        if fn["avg_total_tokens"] and cli["avg_total_tokens"]:
            ratio = fn["avg_total_tokens"] / cli["avg_total_tokens"]
            if ratio >= 1.25 or ratio <= 0.8:
                cheaper = "CLI" if ratio > 1 else "Function"
                headlines.append(
                    f"On {model}, {cheaper} agent used {abs(1 - ratio) * 100:.0f}% "
                    f"{'fewer' if cheaper == 'CLI' else 'more'} tokens per task on average "
                    f"(function {fn['avg_total_tokens']:.0f} vs cli {cli['avg_total_tokens']:.0f})."
                )
    return headlines


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate report from runs/latest-summary.json")
    parser.add_argument("--summary", type=Path, default=Path("runs/latest-summary.json"))
    parser.add_argument("--out-dir", type=Path, default=Path("runs"))
    args = parser.parse_args()

    summary = load_summary(args.summary)
    by_model = summary.get("aggregates_by_model", {})
    if not by_model:
        raise SystemExit("aggregates_by_model is empty in the summary — nothing to chart.")

    charts_dir = args.out_dir / "charts"
    charts_dir.mkdir(parents=True, exist_ok=True)
    chart_files: list[Path] = []
    for key, title, fmt in METRICS:
        out_path = charts_dir / f"{key}.png"
        chart_metric(by_model, key, title, fmt, out_path)
        chart_files.append(out_path)

    findings_path = Path("FINDINGS.md")
    render_findings(summary, chart_files, findings_path)
    print(f"Charts written to {charts_dir}/")
    print(f"Findings written to {findings_path}")


if __name__ == "__main__":
    main()
